import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';

const API = 'http://localhost:4000';

// The API restarts on every file change (tsx watch); during that gap the proxy gets ECONNREFUSED.
// Answer HTTP with 503 and drop sockets quietly so the dev console isn't flooded.
const quietProxy = (proxy: any) => {
  proxy.on('error', (err: NodeJS.ErrnoException, _req: unknown, res: any) => {
    if (err.code !== 'ECONNREFUSED' && err.code !== 'ECONNRESET') console.warn(`[proxy] ${err.message}`);
    if (res && typeof res.writeHead === 'function' && !res.headersSent) {
      res.writeHead(503, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: { code: 'API_RESTARTING', message: 'API is restarting, retry in a moment.' } }));
    } else if (res && typeof res.destroy === 'function') {
      res.destroy();
    }
  });
};

export default defineConfig({
  plugins: [react(), tailwindcss()],
  server: {
    port: 5173,
    proxy: {
      '/api': { target: API, configure: quietProxy },
      // Crawler files are generated by the API from the SEO settings.
      '/robots.txt': { target: API, rewrite: () => '/api/seo/robots.txt', configure: quietProxy },
      '/sitemap.xml': { target: API, rewrite: () => '/api/seo/sitemap.xml', configure: quietProxy },
      '/socket.io': { target: API, ws: true, configure: quietProxy },
    },
  },
});
